const assert = require("node:assert/strict")
const settings = require("../Settings.js")
const original = {sync: {intervalSec: 3}, filter: {mode: "whitelist", patterns: ["a"]}, history: {enabled: false}}
const before = settings.snapshot({refreshIntervalSec: 3, filterEnabled: true, historyEnabled: false, id: "io.github.infinifar.omaclipsync"})
const changed = settings.changed(before, settings.snapshot({refreshIntervalSec: 60, filterEnabled: true, historyEnabled: false}))
assert.deepEqual(changed, {refreshIntervalSec: 60})
assert.equal(settings.merge(original, changed).sync.intervalSec, 60)
assert.equal(settings.merge(original, changed).filter.mode, "whitelist")
assert.equal(original.sync.intervalSec, 3)
assert.equal(settings.merge(original, {filterEnabled: false}).filter.mode, "off")
assert.equal(settings.merge({sync: {}, filter: {mode: "off"}, history: {}}, {filterEnabled: true}).filter.mode, "blacklist")
assert.deepEqual(settings.values(original), {refreshIntervalSec: 30, filterEnabled: true, historyEnabled: false})
assert.equal(settings.merge(original, {refreshIntervalSec: 3}).sync.intervalSec, 30)
